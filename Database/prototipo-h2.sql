-- Esquema de la base de datos del prototipo SGPI (H2).
-- La aplicación lo crea sola al iniciar (com.sgpi.data.DataService.init); este archivo es la referencia.
-- Las tablas observaciones, notificaciones e historial_planes y las columnas marcadas con HU-017
-- se agregaron para el flujo de aprobación y retroalimentación de planes de acción.
-- Las columnas marcadas con HU-001 controlan el bloqueo de la cuenta tras 3 intentos fallidos, y la
-- tabla actividades (HU-002 y HU-004) guarda las actividades de cada plan para calcular su avance.
--
-- Este esquema solo cubre lo que el prototipo implementa (HU-001, HU-002, HU-004, HU-017 y parte de HU-006).
-- No tiene evidencias (HU-003, HU-016) ni evaluación de cierre (HU-020): esas tablas están en el modelo
-- objetivo, Database/modelo-objetivo-postgresql.sql.

CREATE TABLE IF NOT EXISTS usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL,
    correo VARCHAR(180) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    rol VARCHAR(30) NOT NULL,                    -- ADMIN, COORDINADOR, RESPONSABLE o DIRECTOR
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    area VARCHAR(150),                           -- HU-017: área del director
    intentos_fallidos INT NOT NULL DEFAULT 0,    -- HU-001: intentos fallidos seguidos
    bloqueado_hasta TIMESTAMP                    -- HU-001: fin del bloqueo de 15 minutos
);

CREATE TABLE IF NOT EXISTS planes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(50) UNIQUE,
    objetivo VARCHAR(500) NOT NULL,
    area VARCHAR(150) NOT NULL,
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE NOT NULL,
    estado VARCHAR(30) NOT NULL,                 -- BORRADOR, PENDIENTE DE REVISION, EN REVISION,
                                                 -- APROBADO, EN EJECUCION o FINALIZADO
    creado_por BIGINT NOT NULL,
    fecha_envio TIMESTAMP,                       -- HU-017: último envío a revisión
    revisado_por BIGINT,                         -- HU-017: director que aprobó o devolvió
    fecha_revision TIMESTAMP,                    -- HU-017: fecha de la última revisión
    FOREIGN KEY (creado_por) REFERENCES usuarios(id)
);

-- HU-017: observaciones del director al devolver un plan.
CREATE TABLE IF NOT EXISTS observaciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_id BIGINT NOT NULL,
    autor_id BIGINT NOT NULL,
    descripcion VARCHAR(1000) NOT NULL,
    fecha TIMESTAMP NOT NULL,
    atendida BOOLEAN NOT NULL DEFAULT FALSE,
    fecha_atencion TIMESTAMP,
    FOREIGN KEY (plan_id) REFERENCES planes(id) ON DELETE CASCADE,
    FOREIGN KEY (autor_id) REFERENCES usuarios(id)
);

-- HU-017: avisos al coordinador cuando su plan se aprueba o se devuelve.
CREATE TABLE IF NOT EXISTS notificaciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL,
    plan_id BIGINT,
    mensaje VARCHAR(1200) NOT NULL,
    fecha TIMESTAMP NOT NULL,
    leida BOOLEAN NOT NULL DEFAULT FALSE,
    FOREIGN KEY (usuario_id) REFERENCES usuarios(id),
    FOREIGN KEY (plan_id) REFERENCES planes(id) ON DELETE CASCADE
);

-- HU-017 / RNF-10: cada cambio de estado del plan, con el estado anterior y el nuevo.
-- No tiene llave foránea hacia planes para que el historial se conserve si el plan se elimina.
CREATE TABLE IF NOT EXISTS historial_planes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_id BIGINT NOT NULL,
    codigo_plan VARCHAR(50),
    usuario_id BIGINT NOT NULL,
    accion VARCHAR(40) NOT NULL,                 -- CREACION, MODIFICACION, ELIMINACION, ENVIO_REVISION,
                                                 -- APROBACION, DEVOLUCION, OBSERVACION_ATENDIDA,
                                                 -- INICIO_EJECUCION, FINALIZACION, ACTIVIDAD_AGREGADA,
                                                 -- ACTIVIDAD_ELIMINADA o AVANCE_ACTIVIDAD
    estado_anterior VARCHAR(30),
    estado_nuevo VARCHAR(30),
    detalle VARCHAR(1000),
    fecha TIMESTAMP NOT NULL,
    FOREIGN KEY (usuario_id) REFERENCES usuarios(id)
);

-- HU-002 y HU-004: actividades del plan. El avance del plan es actividades FINALIZADA / total.
CREATE TABLE IF NOT EXISTS actividades (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_id BIGINT NOT NULL,
    descripcion VARCHAR(300) NOT NULL,
    responsable_id BIGINT,                       -- usuario con rol RESPONSABLE; puede quedar sin asignar
    fecha_limite DATE NOT NULL,                  -- dentro de las fechas del plan
    estado VARCHAR(20) NOT NULL,                 -- PENDIENTE, EN PROGRESO o FINALIZADA
    FOREIGN KEY (plan_id) REFERENCES planes(id) ON DELETE CASCADE,
    FOREIGN KEY (responsable_id) REFERENCES usuarios(id)
);

-- HU-003: evidencias documentales. Cada evidencia pertenece a una actividad (RN-03) y una actividad
-- solo pasa a FINALIZADA si tiene al menos una. El archivo se guarda en la base (máximo 10 MB).
CREATE TABLE IF NOT EXISTS evidencias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actividad_id BIGINT NOT NULL,
    nombre_archivo VARCHAR(255) NOT NULL,
    formato VARCHAR(10) NOT NULL,                -- PDF, DOCX, JPG o PNG
    tamano BIGINT NOT NULL,                      -- en bytes
    contenido BLOB NOT NULL,
    cargado_por BIGINT NOT NULL,
    cargado_en TIMESTAMP NOT NULL,
    FOREIGN KEY (actividad_id) REFERENCES actividades(id) ON DELETE CASCADE,
    FOREIGN KEY (cargado_por) REFERENCES usuarios(id)
);
