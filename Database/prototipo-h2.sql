-- Esquema de la base de datos del prototipo SGPI (H2).
-- La aplicación lo crea sola al iniciar (Main.DataService.init); este archivo es la referencia.
-- Las tablas observaciones, notificaciones e historial_planes y las columnas marcadas con HU-017
-- se agregaron para el flujo de aprobación y retroalimentación de planes de acción.

CREATE TABLE IF NOT EXISTS usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL,
    correo VARCHAR(180) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    rol VARCHAR(30) NOT NULL,                    -- ADMIN, COORDINADOR, RESPONSABLE o DIRECTOR
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    area VARCHAR(150)                            -- HU-017: área del director
);

CREATE TABLE IF NOT EXISTS planes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(50) UNIQUE,
    objetivo VARCHAR(500) NOT NULL,
    area VARCHAR(150) NOT NULL,
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE NOT NULL,
    estado VARCHAR(30) NOT NULL,                 -- BORRADOR, PENDIENTE DE REVISION, EN REVISION,
                                                 -- APROBADO, EN EJECUCION o FINALIZADO
    creado_por BIGINT NOT NULL,
    fecha_envio TIMESTAMP,                       -- HU-017: último envío a revisión
    revisado_por BIGINT,                         -- HU-017: director que aprobó o devolvió
    fecha_revision TIMESTAMP,                    -- HU-017: fecha de la última revisión
    FOREIGN KEY (creado_por) REFERENCES usuarios(id)
);

-- HU-017: observaciones del director al devolver un plan.
CREATE TABLE IF NOT EXISTS observaciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_id BIGINT NOT NULL,
    autor_id BIGINT NOT NULL,
    descripcion VARCHAR(1000) NOT NULL,
    fecha TIMESTAMP NOT NULL,
    atendida BOOLEAN NOT NULL DEFAULT FALSE,
    fecha_atencion TIMESTAMP,
    FOREIGN KEY (plan_id) REFERENCES planes(id) ON DELETE CASCADE,
    FOREIGN KEY (autor_id) REFERENCES usuarios(id)
);

-- HU-017: avisos al coordinador cuando su plan se aprueba o se devuelve.
CREATE TABLE IF NOT EXISTS notificaciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL,
    plan_id BIGINT,
    mensaje VARCHAR(1200) NOT NULL,
    fecha TIMESTAMP NOT NULL,
    leida BOOLEAN NOT NULL DEFAULT FALSE,
    FOREIGN KEY (usuario_id) REFERENCES usuarios(id),
    FOREIGN KEY (plan_id) REFERENCES planes(id) ON DELETE CASCADE
);

-- HU-017 / RNF-10: cada cambio de estado del plan, con el estado anterior y el nuevo.
-- No tiene llave foránea hacia planes para que el historial se conserve si el plan se elimina.
CREATE TABLE IF NOT EXISTS historial_planes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_id BIGINT NOT NULL,
    codigo_plan VARCHAR(50),
    usuario_id BIGINT NOT NULL,
    accion VARCHAR(40) NOT NULL,                 -- CREACION, ENVIO_REVISION, APROBACION, DEVOLUCION,
                                                 -- OBSERVACION_ATENDIDA, INICIO_EJECUCION o FINALIZACION
    estado_anterior VARCHAR(30),
    estado_nuevo VARCHAR(30),
    detalle VARCHAR(1000),
    fecha TIMESTAMP NOT NULL,
    FOREIGN KEY (usuario_id) REFERENCES usuarios(id)
);
